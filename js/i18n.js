// i18n Class
class I18n {
  constructor() {
    this.currentLang = this.getStoredLanguage() || this.detectLanguage();
    this.init();
  }

  detectLanguage() {
    const browserLang = navigator.language || navigator.userLanguage;
    if (browserLang.startsWith("pt")) return "pt-BR";
    if (browserLang.startsWith("es")) return "es";
    return "en";
  }

  getStoredLanguage() {
    return localStorage.getItem("portfolio-language");
  }

  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem("portfolio-language", lang);
      this.updatePageContent();
      this.updateLanguageSelector();
      document.documentElement.lang = lang === "pt-BR" ? "pt-BR" : lang;
    }
  }

  t(key) {
    return (
      translations[this.currentLang]?.[key] || translations["en"][key] || key
    );
  }

  init() {
    document.addEventListener("DOMContentLoaded", () => {
      this.updatePageContent();
      this.createLanguageSelector();
    });
  }

  createLanguageSelector() {
    const selector = document.createElement("div");
    selector.className = "language-selector";
    selector.innerHTML = `
            <button class="lang-btn" id="langToggle">
                <i class="fas fa-globe"></i>
                <span id="currentLangText">${this.getLangLabel(this.currentLang)}</span>
                <i class="fas fa-chevron-down"></i>
            </button>
            <div class="lang-dropdown" id="langDropdown">
                <button class="lang-option ${this.currentLang === "en" ? "active" : ""}" data-lang="en">
                    <span class="flag">🇺🇸</span> English
                </button>
                <button class="lang-option ${this.currentLang === "pt-BR" ? "active" : ""}" data-lang="pt-BR">
                    <span class="flag">🇧🇷</span> Português
                </button>
                <button class="lang-option ${this.currentLang === "es" ? "active" : ""}" data-lang="es">
                    <span class="flag">🇪🇸</span> Español
                </button>
            </div>
        `;

    document.body.appendChild(selector);

    // Toggle dropdown
    document.getElementById("langToggle").addEventListener("click", (e) => {
      e.stopPropagation();
      document.getElementById("langDropdown").classList.toggle("show");
    });

    // Language selection
    document.querySelectorAll(".lang-option").forEach((btn) => {
      btn.addEventListener("click", (e) => {
        const lang = e.currentTarget.getAttribute("data-lang");
        this.setLanguage(lang);
        document.getElementById("langDropdown").classList.remove("show");
      });
    });

    // Close dropdown on outside click
    document.addEventListener("click", () => {
      document.getElementById("langDropdown").classList.remove("show");
    });
  }

  getLangLabel(lang) {
    const labels = { en: "EN", "pt-BR": "PT", es: "ES" };
    return labels[lang] || "EN";
  }

  updateLanguageSelector() {
    const currentLangText = document.getElementById("currentLangText");
    if (currentLangText) {
      currentLangText.textContent = this.getLangLabel(this.currentLang);
    }

    document.querySelectorAll(".lang-option").forEach((btn) => {
      const lang = btn.getAttribute("data-lang");
      btn.classList.toggle("active", lang === this.currentLang);
    });
  }

  updatePageContent() {
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.getAttribute("data-i18n");
      const translation = this.t(key);

      if (element.hasAttribute("data-i18n-html")) {
        element.innerHTML = translation;
      } else {
        element.textContent = translation;
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      const key = element.getAttribute("data-i18n-placeholder");
      element.placeholder = this.t(key);
    });

    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
      const key = element.getAttribute("data-i18n-title");
      element.title = this.t(key);
    });
  }
}

// Initialize i18n
const i18n = new I18n();

// Export for global access
window.i18n = i18n;
